function extractLayoutChildren(tsx) {
  const open = "<LegalPageLayout";
  const start = tsx.indexOf(open);
  if (start < 0) throw new Error("LegalPageLayout not found");
  const gt = tsx.indexOf(">", start);
  if (gt < 0) throw new Error("LegalPageLayout tag not closed");
  const innerStart = gt + 1;
  const close = "</LegalPageLayout>";
  const end = tsx.lastIndexOf(close);
  if (end < 0) throw new Error("closing LegalPageLayout not found");
  return tsx.slice(innerStart, end).trim();
}

function tsxChildrenToHtml(fragment) {
  let html = fragment;
  html = html.replace(/\bclassName=/g, "class=");
  html = html.replace(/&apos;/g, "'");
  html = html.replace(/&quot;/g, '"');
  html = html.replace(/&amp;/g, "&");
  return html.trim();
}

function sqlQuoteTag(slug) {
  return `yasal_${slug.replace(/[^a-z0-9]/gi, "_")}`;
}

const outfile = path.join(root, "supabase/migrations/20260504120001_yasal_metinler_seed.sql");

const values = [];

for (const p of PAGES) {
  const full = fs.readFileSync(path.join(root, p.file), "utf8");
  const inner = extractLayoutChildren(full);
  const html = tsxChildrenToHtml(inner);
  const tag = sqlQuoteTag(p.slug);
  const escMeta = p.meta.replace(/'/g, "''");
  values.push(`(
  '${p.slug}',
  '${p.baslik.replace(/'/g, "''")}',
  NULL,
  '${escMeta}',
  NULL,
  $${tag}$${html}$${tag}$,
  NULL
)`);
}

const sql = `-- Auto-generated by scripts/gen-yasal-metinler-seed.mjs - do not edit by hand
-- Turkish legal copy migrated from existing page.tsx files

INSERT INTO public.yasal_metinler (slug, baslik, baslik_en, meta_aciklama, meta_aciklama_en, icerik, icerik_en)
VALUES
${values.join(",\n")}
ON CONFLICT (slug) DO UPDATE SET
  baslik = EXCLUDED.baslik,
  meta_aciklama = EXCLUDED.meta_aciklama,
  icerik = EXCLUDED.icerik;
`;

fs.writeFileSync(outfile, sql, "utf8");
console.error("Wrote", outfile);
